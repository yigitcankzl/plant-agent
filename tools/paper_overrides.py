"""Generate the paper-theme overrides for web/plant.html: every rule that paints a dark surface or light text for the
old dark desk gets a body.process override by meaning (red = fail, green = pass, amber = open, violet/teal = ink,
neutral = paper/ink). Rewrites the block between the markers in web/paper.css. Run: python tools/paper_overrides.py"""
import colorsys, re, sys

SRC, OUT = "web/plant.html", "web/paper.css"
BEGIN, END = "/* --- generated by tools/paper_overrides.py --- */", "/* --- end generated --- */"
HEX = re.compile(r"#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b")


def rgb(h):
    h = h if len(h) == 6 else "".join(c * 2 for c in h)
    return [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]


def lum(c):
    r, g, b = rgb(c)
    return .2126 * r + .7152 * g + .0722 * b


def meaning(c):
    r, g, b = rgb(c)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    h *= 360
    if s < .22 or (l > .85 and s < .5):
        return "neutral"
    if h < 22 or h >= 330:
        return "fail"
    if h < 65:
        return "open"
    if h < 165:
        return "pass"
    return "ink"


TEXT = {"neutral": "var(--fg)", "fail": "var(--stop)", "open": "var(--hold)", "pass": "var(--go)", "ink": "var(--green)"}
SURF = {"neutral": "#ffffff", "fail": "#fbeeea", "open": "#fbf3e3", "pass": "#eaf4ec", "ink": "#f4f8ec"}


def rules(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    css = re.sub(r"@keyframes[^{]*\{(?:[^{}]*\{[^}]*\})*\s*\}", "", css)
    css = re.sub(r"@media[^{]*\{", "", css)          # flatten: an override that also applies on wide screens is harmless
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", css):
        yield m.group(1).strip(), m.group(2)


def main():
    html = open(SRC).read()
    css = "\n".join(re.findall(r"<style>(.*?)</style>", html, flags=re.S))
    out, seen = [], set()
    for sel, body in rules(css):
        if not sel or sel.startswith("@") or "#sheet" in sel or ".sheet" in sel or "story-" in sel or "replay" in sel or ":root" in sel:
            continue
        decl = []
        bgs = [HEX.search(v) for k, v in re.findall(r"(?:^|;)\s*([a-z-]+)\s*:\s*([^;]+)", body) if k in ("background", "background-color")]
        bgs = [b.group(1) for b in bgs if b]
        if re.search(r"background(?:-color)?\s*:\s*var\(--(?:accent|act|go|stop|ok|fail|warn|hold|info)\)", body) or \
                any(.3 <= lum(b) < .75 and meaning(b) != "neutral" for b in bgs):
            continue                                       # a coloured button or badge keeps its own white text
        for prop, val in re.findall(r"(?:^|;)\s*([a-z-]+)\s*:\s*([^;]+)", body):
            m = HEX.search(val)
            if not m:
                continue
            c = m.group(1)
            if prop == "color" and lum(c) > .55:
                decl.append(f"color: {TEXT[meaning(c)]}")
            elif prop in ("background", "background-color") and lum(c) < .3 and "gradient" not in val:
                decl.append(f"background: {SURF[meaning(c)]}")
            elif prop.startswith("border") and lum(c) < .3 and "color" not in prop or prop.startswith("border") and lum(c) < .3:
                k = meaning(c)
                decl.append(f"{prop}: {val.replace(m.group(0), '#cfd7c7' if k == 'neutral' else TEXT[k])}")
        if any(d.startswith("background") for d in decl) and not any(d.startswith("color") for d in decl):
            decl.append("color: var(--fg)")
        if not decl:
            continue
        scoped = ", ".join("body.process " + s.strip().removeprefix("body").strip() if not s.strip().startswith("body.") else
                           s.strip().replace("body.", "body.process.", 1) for s in sel.split(","))
        line = f"{scoped} {{ {'; '.join(decl)}; }}"
        if line not in seen:
            seen.add(line); out.append(line)
    paper = open(OUT).read()
    block = BEGIN + "\n" + "\n".join(out) + "\n" + END
    paper = re.sub(r"\n*" + re.escape(BEGIN) + ".*?" + re.escape(END) + r"\n*", "\n\n", paper, flags=re.S)
    anchor = "/* chrome: white bars"                       # hand-written rules below the block win on equal specificity
    paper = paper.replace(anchor, block + "\n\n" + anchor, 1)
    open(OUT, "w").write(paper)
    print(len(out), "override rules")


if __name__ == "__main__":
    sys.exit(main())
