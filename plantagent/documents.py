"""Engineer documents from a plant workspace: equipment data sheet, calculation sheet, management summary, work order.

Deterministic: every number is copied from the workspace model, a simulator solve, the P&ID, the operating data sheet or
a stored answer, and every table row names that source. Nothing is estimated here; a missing value is written
"to confirm". Each document is saved as a DRAFT artifact (markdown + PDF).

Usage: python -m plantagent.documents <case> <datasheet|calc_sheet|summary|work_order> <subject> [scale] [answer]
"""
