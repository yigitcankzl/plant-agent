def _n(v):
    """4 significant digits, plain notation."""
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        return "to confirm" if v in (None, "") else str(v)
    r = float(f"{v:.4g}")
    return str(int(r)) if r == int(r) and abs(r) < 1e15 else str(r)


def _unit_of(key):
    return next((u for s, u in UNITS if key.endswith(s)), "")


def _table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in r) + " |" for r in rows]
    return out


def _safe(name):
    return re.sub(r"[^A-Za-z0-9._-]+", "_", str(name)).strip("_") or "x"


def _answer(w, index):
    if not w.answers:
        return None, None
    i = int(index) if index is not None and str(index).lstrip("-").isdigit() else len(w.answers) - 1
    if not -len(w.answers) <= i < len(w.answers):
        raise ValueError(f"answer index {index} out of range: {len(w.answers)} answers on record")
    i %= len(w.answers)
    return i, w.answers[i]


def _changed_units(p):
    out = []
    for c in p.get("changes") or []:
        if c.get("add_unit"):
            out.append(c["add_unit"]["id"])
        elif c.get("reroute"):
            out.append(c["reroute"]["unit"])
        elif str(c.get("path", "")).startswith("units."):
            out.append(c["path"].split(".")[1])
    return list(dict.fromkeys(out))


def _proposal(ans, tag):
    """The answer's proposal on this tag: new equipment it adds, its own tag, or the units it changes."""
    props = (ans or {}).get("proposals") or []
    for test in (lambda p: tag in [e["id"] for e in p.get("new_equipment") or added_equipment(p.get("changes") or [])],
                 lambda p: p.get("tag") == tag or p.get("fixes") == tag,
                 lambda p: tag in _changed_units(p)):
        hit = next((p for p in props if test(p)), None)
        if hit:
            return hit
    return None


def _model_unit(w, spec, tag, prop=None):
    ids = [u["id"] for u in spec.get("units") or []]
    if tag in ids:
        return tag, "same tag in the model"
    for uid in _changed_units(prop or {}):
        if uid in ids:
            return uid, "unit changed by the proposal"
    for m in (w.built or {}).get("mapping") or []:
        if m.get("tag") == tag:
            hit = next((u for u in ids if re.search(rf"(?<![\w/-]){re.escape(u)}(?![\w/-])", m.get("modelled_as", "")) and u != tag), None)
            if hit:
                return hit, f"model mapping: {m['modelled_as']}"
    return None, None


def _rev_label(w):
    return f"{(w.built or {}).get('label')} rev {len(w.revisions)}"


def _current(w, scale):
    r = w.state(scale)
    src = f"{_simulator_name(w.cfg)} solve of the current model ({_rev_label(w)}) at {_n(scale * 100)} %" + \
          (" (stored solution)" if r.get("replayed") else "")
    return r, src


def _proposed(w, i, p, scale):
    """Solved proposed case: the answer's stored calculation record at its target, else a fresh solve of the patched model."""
    c = p.get("calculation") or {}
    if c.get("units") and (scale is None or abs(scale - float(c.get("target_scale") or 0)) < 0.006):
        res = {"units": c["units"], "checks": [{**x, "utilisation": x.get("after")} for x in c.get("checks") or []],
               "streams": {s["id"]: s for s in c.get("streams") or []}}
        return res, float(c["target_scale"]), (f"answer {i + 1} proposal '{p.get('title')}': calculation record "
                                               f"({c.get('simulator')}, {_n(float(c['target_scale']) * 100)} %, model {c.get('model_label')})")
    scale = float(scale or w.cfg.get("target_scale", 1.0))
    spec = patch(copy.deepcopy(w.spec), p["changes"])
    res = ro.run(spec, scale) if _is_watertap(w.cfg) else process.run(spec, scale)
    return res, scale, f"{_simulator_name(w.cfg)} solve of answer {i + 1} proposal '{p.get('title')}' on {_rev_label(w)} at {_n(scale * 100)} %"


def _pid_equipment(w, tag):
    return next((e for e in (w.pid or {}).get("equipment") or [] if e.get("tag") == tag), None)


def _sheet_lines(w, *tags):
    pat = re.compile("|".join(rf"(?<![\w-]){re.escape(t)}(?![\w-])" for t in tags if t))
    return [(n, line.strip(" -|")) for n, line in enumerate(w.basis.splitlines(), 1) if pat.search(line)][:14]


def _conditions(res, uid, unit_spec, src):
    rows = []
    for k, v in sorted(((res.get("units") or {}).get(uid) or {}).items()):
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            rows.append((k, _n(v), _unit_of(k), src))
    if unit_spec:
        ins, outs = ports(unit_spec)
        for side, sids in (("inlet", ins), ("outlet", outs)):
            for sid in sids:
                s = (res.get("streams") or {}).get(sid) or {}
                for k in ("T_C", "P_bar", "kg_h", "m3_h", "vapour_frac"):
                    if s.get(k) is not None:
                        rows.append((f"{side} {sid} {k}", _n(s[k]), _unit_of(k), src))
    return rows


def _checks(res, uid):
    return [c for c in res.get("checks") or [] if c.get("id") == uid and c.get("utilisation") is not None]


def _relief(w, tag):
    if not w.cfg.get("pid"):
        return []
    return [x for x in pid.relief_scan(DATA / w.cfg["pid"]) if x["tag"] == tag]


def _connections(w, tag):
    out = []
    for c in (w.pid or {}).get("connections") or []:
        ends = [re.sub(r"\(.*\)$", "", str(c.get(k, ""))) for k in ("from", "to")]
        if tag in ends:
            other = ends[1] if ends[0] == tag else ends[0]
            out.append({"lines": c.get("lines") or [], "other": other, "direction": "out" if ends[0] == tag else "in",
                        "inline": c.get("inline") or []})
    return out


def datasheet(w, tag, scale=None, answer=None):
    i, ans = _answer(w, answer)
    p = _proposal(ans, tag)
    new = next((e for e in (p or {}).get("new_equipment") or added_equipment((p or {}).get("changes") or []) if e["id"] == tag), None)
    if p:
        res, scale, src = _proposed(w, i, p, scale)
        spec = patch(copy.deepcopy(w.spec), p["changes"])
    else:
        scale = float(scale or 1.0)
        res, src = _current(w, scale)
        spec = w.spec
    basis, src = src, f"basis solve ({_n(scale * 100)} %)"  # full description once, short label per row
    uid, why = _model_unit(w, spec, tag, p)
    unit_spec = next((u for u in spec.get("units") or [] if u["id"] == uid), None)
    eq = _pid_equipment(w, tag)
    status = (f"proposed new equipment (answer {i + 1}: {p.get('title')}), rating to confirm" if new else
              f"existing, proposed change in answer {i + 1}: {p.get('title')}" if p else "existing")
    md = [f"# Equipment data sheet: {tag}", "", DRAFT, "",
          *_table(("Field", "Value", "Unit", "Source"), [
              ("Plant", w.cfg["title"], "", f"cases/{w.name}/case.json"),
              ("Tag", tag, "", "P&ID" if eq else ("proposal" if p else "request")),
              ("Equipment class", (eq or {}).get("class") or (unit_spec or {}).get("type") or "to confirm", "",
               f"P&ID {tag}" if eq else "model unit type"),
              ("Status", status, "", f"answer {i + 1}" if p else "P&ID"),
              ("Model unit", uid or "not modelled as its own unit: to confirm", "", why or "model mapping"),
              ("Throughput (basis solve)", _n(scale * 100), "% of today", basis)]), "",
          "## Process conditions (simulator)", ""]
    cond = _conditions(res, uid, unit_spec, src) if uid else []
    md += _table(("Field", "Value", "Unit", "Source"), cond) if cond else ["No solved conditions for this tag: to confirm."]
    design = [(k, v, "", f"P&ID {tag} {k}") for k, v in sorted(((eq or {}).get("design") or {}).items())]
    design += [(k, _n(v), _unit_of(k), f"model spec units.{uid}.{k}" + (" (proposal add_unit)" if new else ""))
               for k, v in sorted((unit_spec or {}).items()) if isinstance(v, (int, float)) and not isinstance(v, bool)]
    md += ["", "## Design data", ""] + (_table(("Field", "Value", "Unit", "Source"), design) if design else ["No design data on record: to confirm."])
    limits = (new or {}).get("limits") or (spec.get("limits") or {}).get(uid) or {}
    rating_src = (new or {}).get("rating_source") or f"model limits.{uid} ({_rev_label(w)})"
    md += ["", "## Ratings (limits the checks use)", ""]
    md += _table(("Rating", "Value", "Unit", "Source"), [(k, _n(v), _unit_of(k), rating_src) for k, v in sorted(limits.items())]) \
        if limits else ["No rating on record: to confirm."]
    checks = _checks(res, uid)
    if checks:
        md += ["", "## Limit checks at this condition", ""]
        md += _table(("Check", "Value", "Limit", "Utilisation", "Source"),
                     [(c["check"], f"{_n(c['value'])} {c.get('unit') or ''}", f"{_n(c['limit'])} {c.get('unit') or ''}",
                       f"{_n(c['utilisation'] * 100)} %", src) for c in checks])
    lines = _sheet_lines(w, tag, uid)
    if lines:
        md += ["", "## Operating data sheet rows on this tag", ""]
        md += _table(("Data sheet text", "Source"), [(t, f"cases/{w.name}/{w.cfg['basis']} line {n}") for n, t in lines])
    relief = _relief(w, tag)
    confirm = (["Vendor curve and guaranteed performance", "Mechanical design and materials of construction",
                "Relief, isolation and control design (not on the as-built P&ID)", f"Rating: {rating_src}"] if new else
               (["Vendor/nameplate data (no design data on the P&ID)"] if not (eq or {}).get("design") else []) +
               ["Materials of construction"] + [f"Relief, {', '.join(x['side_fluids'])} side: {x['status']} ({x['detail']})"
                                                for x in relief if x["status"] != "protected"])
    md += ["", "## To confirm", ""] + [f"- [ ] {c}" for c in confirm]
    return f"Data sheet {tag}", f"datasheet-{_safe(tag)}", md, \
        f"{tag}: {status}; conditions at {_n(scale * 100)} % from {basis}"


def calc_sheet(w, subject, scale=None, answer=None):
    uid, _, want = str(subject).partition(":")
    uid, want = uid.strip(), want.strip().lower()
    i, ans = _answer(w, answer) if answer is not None else (None, None)
    scale = float(scale or (ans and w.cfg.get("target_scale")) or 1.0)
    res, basis = _current(w, scale)
    src = f"basis solve ({_n(scale * 100)} %)"
    checks = [c for c in _checks(res, uid) if want in c["check"].lower()]
    if not checks:
        raise ValueError(f"no limit check on {uid!r}{' matching ' + repr(want) if want else ''} at {scale}; "
                         f"checked units: {sorted({c['id'] for c in res.get('checks') or [] if c.get('utilisation') is not None})}")
    c = max(checks, key=lambda x: x["utilisation"])
    unit_spec = next((u for u in w.spec.get("units") or [] if u["id"] == uid), None)
    method = next((m for k, m in METHODS if k in c["check"]), "utilisation = solved value / stated limit")
    lim_keys = (w.spec.get("limits") or {}).get(uid) or {}
    md = [f"# Calculation sheet: {uid}, {c['check']}", "", DRAFT, "", "## Inputs", ""]
    inputs = [(k, _n(v), _unit_of(k), f"model spec units.{uid}.{k} ({_rev_label(w)})")
              for k, v in sorted((unit_spec or {}).items()) if isinstance(v, (int, float)) and not isinstance(v, bool)]
    inputs += [(f"limit {k}", _n(v), _unit_of(k), f"model limits.{uid}.{k} ({_rev_label(w)})") for k, v in sorted(lim_keys.items())]
    inputs += _conditions(res, uid, unit_spec, src)
    md += _table(("Input", "Value", "Unit", "Source"), inputs)
    md += ["", "## Method", "", method, "", f"Basis solve: {basis}.", "", "## Result", ""]
    md += _table(("Quantity", "Value", "Unit", "Source"), [
        ("value", _n(c["value"]), c.get("unit") or "", src), ("limit", _n(c["limit"]), c.get("unit") or "", src),
        ("utilisation", _n(c["utilisation"] * 100), "%", src),
        ("verdict", "within limit" if c["utilisation"] <= 1 else "over limit", "", src)])
    if ans:
        rows = []
        for p in ans.get("proposals") or []:
            hit = next((x for x in (p.get("calculation") or {}).get("checks") or [] if x.get("id") == uid and x.get("check") == c["check"]), None)
            if hit:
                rows.append((p.get("title"), "yes" if p.get("verified") else "no", f"{_n((hit.get('before') or 0) * 100)} %",
                             f"{_n((hit.get('after') or 0) * 100)} %", f"{_n(hit.get('value'))} {hit.get('unit') or ''}",
                             f"answer {i + 1} calculation record at {_n(float(p['calculation']['target_scale']) * 100)} %"))
        if rows:
            md += ["", f"## Before / after (answer {i + 1}: {ans.get('headline')})", ""]
            md += _table(("Proposal", "Verified", "Before", "After", "Value after", "Source"), rows)
    return f"Calculation {uid} {c['check']}", f"calc-{_safe(uid)}", md, \
        f"{uid} {c['check']}: {_n(c['utilisation'] * 100)} % at {_n(scale * 100)} % ({basis})"


def summary(w, subject=None, scale=None, answer=None):
    i, ans = _answer(w, subject if answer is None else answer)
    if not ans:
        raise ValueError("no answer on record to summarise; ask a question first")
    a_src = f"answer {i + 1} ({ans.get('model')})"
    props = ans.get("proposals") or []
    target = float(next((p["target_scale"] for p in props if p.get("target_scale")), w.cfg.get("target_scale", 1.0)))
    calc = next((p["calculation"] for p in props if p.get("calculation")), None)
    if calc:
        before, b_src = calc.get("capacity_multiple_before"), f"{a_src} calculation record"
    else:
        before, b_src = w.capacity().get("capacity_multiple"), f"{_simulator_name(w.cfg)} capacity of {_rev_label(w)}"
    comb = ans.get("combined") or {}
    lim = comb.get("limited_by") or {}
    md = [f"# Management summary: {w.cfg['title']}", "", DRAFT, "", f"**Question:** {ans.get('request')}", "",
          f"**Decision proposed:** {ans.get('headline')}", "", ans.get("summary") or "", "", f"(Source: {a_src}.)", "",
          "## Capacity", ""]
    md += _table(("Item", "Value", "Source"), [
        ("Target", f"{_n(target * 100)} % of today", f"cases/{w.name}/case.json target_scale / {a_src}"),
        ("Capacity today", f"{_n((before or 0) * 100)} %" if before else "to confirm", b_src),
        ("Capacity with all verified changes", f"{_n(comb['capacity_multiple'] * 100)} %" if comb.get("capacity_multiple") else "to confirm",
         f"{a_src} combined verification"),
        ("First limit after", f"{lim.get('id')} {lim.get('check')} ({_n(lim.get('utilisation', 0) * 100)} %)" if lim else "to confirm",
         f"{a_src} combined verification"),
        ("Reaches target", "yes" if comb.get("reaches_target") else "no", f"{a_src} combined verification")])
    md += ["", "## Changes and cost class", ""]
    md += _table(("Change", "Verified", "Cost class", "Capacity alone", "Source"),
                 [(p.get("title"), "yes" if p.get("verified") else f"no ({p.get('unverified_reason') or 'not verified'})",
                   p.get("cost_class") or "not stated",
                   f"{_n(p['capacity_multiple'] * 100)} %" if p.get("capacity_multiple") else "—", a_src) for p in props]) \
        if props else ["No change to the plant proposed."]
    risks = [(f"Still over at target: {o['id']} {o['check']}", f"{_n(o['utilisation'] * 100)} %", f"{a_src} combined verification")
             for o in comb.get("over_limits_at_target") or []]
    risks += [(f"New equipment {e['id']}: rating to confirm", e.get("rating_source") or "to confirm", a_src)
              for p in props if p.get("verified") for e in p.get("new_equipment") or []]
    review = (w.built or {}).get("review") or {}
    risks += [(f"Model review {f.get('severity')}: {f.get('check')}", f.get("evidence") or "", "model review of the current model")
              for f in review.get("findings") or []]
    tags = {t for p in props if p.get("verified") for t in [p.get("tag"), *_changed_units(p)] if t}
    risks += [(f"Relief on {x['tag']} {', '.join(x['side_fluids'])} side", f"{x['status']}: {x['detail']}", "P&ID relief scan")
              for t in sorted(tags) for x in _relief(w, t) if x["status"] != "protected"]
    md += ["", "## Risks", ""] + (_table(("Risk", "Detail", "Source"), risks) if risks else ["No open risk on record."])
    approve = [(describe_change(w.spec, ch, w.names()), p.get("title"), a_src)
               for p in props if p.get("verified") for ch in p.get("changes") or []]
    md += ["", "## What needs approval (management of change)", ""]
    md += _table(("Change", "Part of", "Source"), [(re.sub("<[^>]+>", "", c), t, s) for c, t, s in approve]) if approve else ["Nothing to approve."]
    if ans.get("field_checks"):
        md += ["", "## Field checks before approval", ""]
        md += _table(("Check", "Where / how", "Source"), [(f.get("item"), f.get("where"), a_src) for f in ans["field_checks"]])
    return f"Summary of answer {i + 1}", f"summary-answer-{i + 1}", md, f"{ans.get('headline')} ({a_src})"


def work_order(w, tag, scale=None, answer=None):
    i, ans = _answer(w, answer)
    p = _proposal(ans, tag)
    if not p:
        raise ValueError(f"no proposal on {tag!r} in the answer on record; a work order needs the task and its expected effect")
    a_src = f"answer {i + 1} ({ans.get('model')})"
    eq = _pid_equipment(w, tag)
    units = set(_changed_units(p)) | {tag}
    md = [f"# Maintenance work order: {p.get('title')}", "", DRAFT, "", "## Equipment and task", ""]
    md += _table(("Field", "Value", "Source"), [
        ("Plant", w.cfg["title"], f"cases/{w.name}/case.json"), ("Equipment", tag, "P&ID" if eq else a_src),
        ("Class", (eq or {}).get("class") or "to confirm", f"P&ID {tag}" if eq else "not on the P&ID"),
        ("Task", p.get("title"), a_src), ("Why", p.get("why") or "to confirm", a_src),
        ("Cost class", p.get("cost_class") or "not stated", a_src),
        ("Verified in the simulator", "yes" if p.get("verified") else f"no ({p.get('unverified_reason')})", a_src)])
    md += ["", "## Changes this work makes to the model", ""]
    md += _table(("Change", "Source"), [(re.sub("<[^>]+>", "", describe_change(w.spec, ch, w.names())), a_src) for ch in p.get("changes") or []])
    iso = []
    for c in _connections(w, tag):
        valves = [v for v in c["inline"] if "Safety" not in v]
        iso.append((", ".join(c["lines"]), f"{c['direction']} {'from' if c['direction'] == 'in' else 'to'} {c['other']}",
                    ", ".join(valves) or "no valve on this line: isolate at the next item / blind", f"P&ID line {', '.join(c['lines'])}"))
    md += ["", "## Isolation points (P&ID)", ""]
    md += _table(("Line", "Connects", "Valves to close and lock", "Source"), iso) if iso else ["No P&ID connections on this tag: isolation to confirm."]
    relief = _relief(w, tag)
    if relief:
        md += ["", "## Relief while isolated (P&ID relief scan)", ""]
        md += _table(("Side", "Status", "Detail", "Source"), [(", ".join(x["side_fluids"]), x["status"], x["detail"], "P&ID relief scan") for x in relief])
    checks = [f for f in ans.get("field_checks") or [] if any(u in " ".join(str(v) for v in f.values()) for u in units)] or ans.get("field_checks") or []
    md += ["", "## Acceptance check (from the answer's field checks)", ""]
    md += _table(("Check", "Where / how", "What it changes", "Source"), [(f.get("item"), f.get("where"), f.get("changes"), a_src) for f in checks]) \
        if checks else ["No field check on record: acceptance check to confirm."]
    calc = p.get("calculation") or {}
    eff = [(f"{x['id']} {x['check']}", f"{_n((x.get('before') or 0) * 100)} %", f"{_n((x.get('after') or 0) * 100)} %",
            f"{a_src} calculation record at {_n(float(calc['target_scale']) * 100)} %")
           for x in calc.get("checks") or [] if x.get("id") in units and x.get("before") is not None]
    if calc.get("capacity_multiple_after"):
        eff.append(("plant capacity", f"{_n(calc['capacity_multiple_before'] * 100)} %", f"{_n(calc['capacity_multiple_after'] * 100)} %",
                    f"{a_src} calculation record"))
    md += ["", "## Expected effect (verified proposal)", ""]
    md += _table(("Quantity", "Before", "After", "Source"), eff) if eff else ["No verified calculation record: expected effect to confirm."]
    md += ["", "## Sign-off", ""] + _table(("Role", "Name", "Signature", "Date"),
                                           [("Maintenance planner", "", "", ""), ("Operations (isolation)", "", "", ""),
                                            ("Process engineer (acceptance)", "", "", "")])
    return f"Work order {tag}: {p.get('title')}", f"workorder-{_safe(tag)}", md, f"{p.get('title')} ({a_src})"


def make(w, kind, subject=None, scale=None, answer=None, by=None, request=None):
    """Build one document and save it as a draft artifact; returns the artifact meta."""
    from .decision import _pdf
    if kind not in KINDS:
        raise ValueError(f"document kind must be one of {list(KINDS)}")
    if not w.built:
        raise ValueError("no model built yet")
    title, stem, md, summary_ = {"datasheet": datasheet, "calc_sheet": calc_sheet, "summary": summary,
                                 "work_order": work_order}[kind](w, subject, float(scale) if scale else None, answer)
    text = "\n".join(md) + "\n"
    files = {f"{stem}.md": text}
    try:
        import tempfile
        from pathlib import Path
        with tempfile.TemporaryDirectory() as d:
            _pdf(text, Path(d) / "x.pdf")
            files[f"{stem}.pdf"] = (Path(d) / "x.pdf").read_bytes()
    except Exception as e:  # noqa: BLE001 - the markdown stands without the PDF
        summary_ += f" (PDF failed: {type(e).__name__}: {e})"
    sources = sorted({r.split("|")[-2].strip() for r in md if r.startswith("|") and not r.startswith("|---") and r.count("|") > 2} - {"Source"})
    return artifacts.save(w.name, KINDS[kind], title, files, by=by or "PlantAgent (deterministic)", request=request,
                          sources=sources[:40], summary=summary_)


